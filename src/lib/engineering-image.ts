export const ENGINEERING_IMAGE_PROMPT = [
  '工程图像精修规范：第1张原图是本次编辑的主画布。其他参考图只辅助理解用户指定的修改，不能替代主画布，也不默认拼接成新画面。',
  '编辑范围以用户明确要求为准，只修改被指定的区域或内容；用户明确要求整体调整时，只执行该项整体调整。未涉及的位置和信息默认保持原样，不将画面重新设计。',
  '对于工程照片和效果图，默认保留未指定修改处的工程结构、构件关系、透视、遮挡、轮廓、纹理、材质与光影。对于图纸，默认保留未指定修改处的几何线条、尺寸标注、编号、符号和现有文字。',
  '未明确要求时，不凭空增删工程构件，不自行修改尺寸、连接关系或工程数据。不清楚的文字、标注和细节保留现状，不补编、不猜测修正；用户提供明确替换内容时，按该内容修改。',
  '默认保持原图的画幅、方向、比例和像素尺寸，不裁切、不扩图，不添加边框或留白，不通过拉伸改变主体比例。',
  '用户明确要求优先于默认保留规则：若要求改某个构件、文字、尺寸标注或编号，就只按其明确给出的范围和内容修改，不用默认保留规则阻止该项编辑。',
  '输出编辑后的图像，不额外生成手机界面、对比面板、说明文字或标题。用户明确要求加入文字或图形时，仅在指定位置按给定内容编辑。',
].join('\n');

export function engineeringImagePrompt(instruction: string): string {
  const request = instruction.trim();
  if (!request) throw Error('请说明需要修改的位置和内容');
  return `${ENGINEERING_IMAGE_PROMPT}\n\n【本次用户编辑要求】\n${request}`;
}
